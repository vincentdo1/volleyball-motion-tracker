import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { clipGolden } from '../fixtures/clips.ts';
import { trackLabels } from '../fixtures/tracks.ts';
import { bakeoffDir } from '../harness/io.ts';

const runs = Object.entries(trackLabels.clips);

describe('track labels', () => {
  it('cover the three consecutive runs', () => {
    expect(runs.map(([name]) => name).sort()).toEqual(['beach', 'gtu', 'px330']);
  });

  it.each(runs)('%s: 60 consecutive presentable frames, keyed by the clip PTS table', (_, clip) => {
    const table = clipGolden(clip.video).video.ptsUs;
    const start = table.indexOf(clip.frames[0]?.ptsUs ?? -1);
    expect(start).toBeGreaterThanOrEqual(0);
    expect(clip.frames.map((f) => f.ptsUs)).toEqual(table.slice(start, start + 60));
  });

  it.each(runs)('%s: ids are unique per frame, numbered by first appearance, boxes inside the frame', (_, clip) => {
    let next = 1;
    const seen = new Set<number>();
    for (const frame of clip.frames) {
      const ids = frame.persons.map((p) => p.id);
      expect(new Set(ids).size).toBe(ids.length);
      for (const person of frame.persons) {
        if (!seen.has(person.id)) {
          expect(person.id).toBe(next++);
          seen.add(person.id);
        }
        const [x0, y0, x1, y1] = person.box;
        expect(x0).toBeGreaterThanOrEqual(-1);
        expect(y0).toBeGreaterThanOrEqual(-1);
        expect(x1).toBeLessThanOrEqual(clip.width + 1);
        expect(y1).toBeLessThanOrEqual(clip.height + 1);
      }
    }
  });

  it.skipIf(!existsSync(join(bakeoffDir(), 'teacher.json')))('are regenerated byte-identically', () => {
    const script = resolve(import.meta.dirname, '../tools/make-tracks.ts');
    expect(() => execFileSync('node', [script, '--check'], { stdio: 'pipe' })).not.toThrow();
  });
});
