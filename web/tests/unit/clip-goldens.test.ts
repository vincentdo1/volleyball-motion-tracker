import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { clipGolden, clipGoldens } from '../fixtures/clips';

const script = resolve(import.meta.dirname, '../tools/make-clip-goldens.mjs');
const names = Object.keys(clipGoldens.clips);

describe('clip goldens', () => {
  it('cover all 11 test clips', () => {
    expect(names).toHaveLength(11);
  });

  it('keep the edit-list clips honest: negative-PTS packets are counted and excluded', () => {
    const att03 = clipGolden('volleyball_spike_attempt_03.mp4').video;
    const att04 = clipGolden('volleyball_spike_attempt_04.mp4').video;
    expect([att03.negativePtsPackets, att03.presentableFrames, att03.packetCount]).toEqual([46, 241, 287]);
    expect([att04.negativePtsPackets, att04.presentableFrames, att04.packetCount]).toEqual([31, 181, 212]);
    expect(att03.firstRawPtsUs).toBeLessThan(0);
    expect(att04.firstRawPtsUs).toBeLessThan(0);
  });

  it('records the 167 ms last-frame gap of attempt_03', () => {
    expect(clipGolden('volleyball_spike_attempt_03.mp4').video.lastDeltaUs).toBe(166_666);
  });

  it.each(names)('%s has a strictly ascending, non-negative integer PTS table that matches its summary', (name) => {
    const { video } = clipGolden(name);
    expect(video.ptsUs).toHaveLength(video.presentableFrames);
    expect(video.packetCount - video.negativePtsPackets).toBe(video.presentableFrames);
    expect(video.ptsUs[0]).toBe(video.firstPtsUs);
    expect(video.ptsUs.at(-1)).toBe(video.lastPtsUs);
    expect(video.ptsUs.every(Number.isInteger)).toBe(true);
    expect(video.ptsUs.every((pts, i) => pts >= 0 && (i === 0 || pts > (video.ptsUs[i - 1] ?? 0)))).toBe(true);
    expect(video.variableFrameRate).toBe(false);
  });

  it('are regenerated byte-identically from the clips', () => {
    expect(() => execFileSync('node', [script, '--check'], { stdio: 'pipe' })).not.toThrow();
  });
});
